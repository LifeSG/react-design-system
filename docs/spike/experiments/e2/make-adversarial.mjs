// Usage: node make-adversarial.mjs <library dir>
// Spike 01 / E4: writes src/app/adversarial/textarea-child-last/forced.css, which repeats
// the two real rules of the F10 pair in the hostile source order: the parent's rule
// (input-textarea `margin-top: 0`) FIRST, the child's rule (form-label `margin-top: 8px`)
// SECOND, each wrapped in the layer it has in this library build. If both rules end up
// in one layer, source order decides and the child wins (8px, wrong); only a layer order
// that ranks the parent's layer later keeps 0px.
// The class names are read from the built CSS, so the rules match the real component.
import fs from "node:fs";
import path from "node:path";

const lib = path.resolve(process.argv[2]);
const read = (dir, prefix) => {
    const f = fs
        .readdirSync(path.join(lib, dir))
        .find((n) => n.startsWith(prefix) && n.endsWith(".css"));
    return fs.readFileSync(path.join(lib, dir, f), "utf8");
};
const textarea = read("input-textarea", "textarea.styles_");
const formLabel = read("form/form-label", "form-label.styles_");

// layer path the file's rules live in: "" (published), "fds", or "fds" + inner name
const layerOf = (css) => {
    const m = css.match(/^@layer fds\{@layer ([a-z0-9-]+)\{/);
    if (m) return ["fds", m[1]];
    return css.startsWith("@layer fds{") ? ["fds"] : [];
};
const wrap = (layers, rule) =>
    layers.reduceRight((inner, l) => `@layer ${l}{${inner}}`, rule);

const parent = textarea.match(
    /\.([a-z0-9]+)\{[^}]*flex:1;margin-top:0;[^}]*\}/
);
const child = formLabel.match(
    /\.([a-z0-9]+)\{[^}]*margin-top:var\(--fds-spacing-8\);[^}]*\}/
);
if (!parent || !child)
    throw new Error("could not find the F10 rules in " + lib);

const out = [
    "/* generated by make-adversarial.mjs: F10 pair in hostile source order */",
    wrap(layerOf(textarea), `.${parent[1]}{margin-top:0}`),
    wrap(layerOf(formLabel), `.${child[1]}{margin-top:var(--fds-spacing-8)}`),
].join("\n");
fs.writeFileSync(
    "src/app/adversarial/textarea-child-last/forced.css",
    out + "\n"
);
console.log(out);
