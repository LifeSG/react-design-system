// Usage: node make-overrides.mjs
// Spike 01 / E9: writes src/app/overrides/<mech>/{page.jsx, override.css,
// override.module.css} from overrides-spec.mjs. Every page imports the theme stylesheet
// first (the documented setup), then its consumer CSS, then renders the same targets.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { MECHS, TARGETS, cls } from "./overrides-spec.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "src/app/overrides");

for (const m of MECHS) {
    if (m.tailwind) {
        // compile only this page's classes; 14b puts fds between base and components
        const dir = path.join(root, m.id);
        const input = path.join(dir, "tailwind.input.css");
        const order =
            m.tailwind === "fds"
                ? "@layer theme, base, fds, components, utilities;\n"
                : "";
        fs.writeFileSync(
            input,
            // stylelint-disable: Tailwind syntax and generated class names are not ours to lint
            `/* stylelint-disable */\n/* E9 ${m.id}: Tailwind v4 input */\n${order}@import "tailwindcss" source(none);\n@source "./page.jsx";\n`
        );
        const out = path.join(dir, "tailwind.css");
        execFileSync(
            path.join(here, "node_modules/.bin/tailwindcss"),
            ["-i", input, "-o", out],
            { cwd: here, stdio: "ignore" }
        );
        fs.writeFileSync(
            out,
            "/* stylelint-disable */\n" + fs.readFileSync(out, "utf8")
        );
        console.log("compiled", path.relative(here, dir) + "/tailwind.css");
    }
    if (m.custom) continue; // hand-written page (Tailwind, styled-components)
    const dir = path.join(root, m.id);
    fs.rmSync(dir, { recursive: true, force: true });
    fs.mkdirSync(dir, { recursive: true });
    const head = `/* E9 ${m.id} (mechanism ${m.n}): ${m.label}. Generated by make-overrides.mjs. */\n`;
    const imports = [
        `import "@lifesg/react-design-system/theme/styles/lifesg.css";`,
    ];
    const props = [];
    if (m.css) {
        fs.writeFileSync(path.join(dir, "override.css"), head + m.css() + "\n");
        imports.push(`import "./override.css";`);
    }
    if (m.cssModule) {
        fs.writeFileSync(
            path.join(dir, "override.module.css"),
            head + m.cssModule() + "\n"
        );
        imports.push(`import mod from "./override.module.css";`);
        const entries = TARGETS.map(
            (t) => `${JSON.stringify(t.id)}: mod[${JSON.stringify(cls(t))}]`
        );
        props.push(`classes={{ ${entries.join(", ")} }}`);
    } else if (m.via === "class") {
        props.push(
            `classes={${JSON.stringify(
                Object.fromEntries(TARGETS.map((t) => [t.id, cls(t)]))
            )}}`
        );
    }
    if (m.styles) props.push(`styles={${JSON.stringify(m.styles())}}`);
    if (m.themeStyle)
        props.push(`themeStyle={${JSON.stringify(m.themeStyle())}}`);
    if (m.applyStyle)
        props.push(`applyStyle={${JSON.stringify(m.applyStyle())}}`);
    imports.push(`\nimport { Targets } from "../targets";`);
    const page = `"use client";
// E9 ${m.id} (mechanism ${m.n}): ${m.label}.
// Built under globals setup "${m.globals}". Generated by make-overrides.mjs.
${imports.join("\n")}

export default function Page() {
    return <Targets ${props.join(" ")} />;
}
`;
    fs.writeFileSync(path.join(dir, "page.jsx"), page);
    console.log("wrote", path.relative(here, dir));
}
